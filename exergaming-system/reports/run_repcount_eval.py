"""
Track B -- rep-counting accuracy at scale, both threshold variants.

Reconstructs the 14 July 2026 Track B batch run, whose script was never
saved (reports/evaluation_results.csv was kept, the code that produced it
was not), and extends it to score every video under BOTH learned-definition
variants in a single pass:

  original    the shipped definitions (min/max extremes) that produced
              every published number
  percentile  the same definitions re-derived with EXTREME_PERCENTILE=2.0

WHY BOTH ARMS ARE RE-RUN, RATHER THAN COMPARING AGAINST THE JULY CSV

The published evaluation_results.csv was produced on 14 July. The rep
cool-down (MIN_REP_DURATION_MS, generic_exercise.py:34) was built on 16
July and tuned to 200 ms on 21 July, so those numbers were generated by an
engine with NO timing floor at all. Comparing a fresh percentile run
against them would attribute the cool-down's effect to the percentile
change. Re-running the original variant under today's engine isolates the
one variable. The July numbers remain on disk as
evaluation_results_pre_percentile.csv -- a record of what was reported at
the viva, not a comparison arm.

METHOD (matching the 14 July run)

Same PoseDetector + GenericExercise components as test_video.py, every
frame processed, no sampling, no PositionGate. Evaluated against the
LEARNED definitions rather than the hardcoded ones, since demonstration-
based learning is the primary contribution and bicep curl has no hardcoded
counterpart. Timestamps are on the video's own timeline
(frame_index / fps * 1000), not wall-clock -- this loop runs faster than
real-time and the cool-down would otherwise reject every rep.

Accuracy, matching test_video.py:
    gt > 0 : max(0, (1 - |detected - gt| / gt) * 100)
    gt = 0 : 100 if detected == 0 else 0   (false-positive check; 10 such
             videos in the set)

Form counts are per COMPLETED REP, not per frame -- same as test_video.py,
which appends the form rating at the moment each rep completes.

ONE DETECTION PASS, TWO SCORERS

MediaPipe output does not depend on the thresholds, so detection runs once
per frame and both variants are fed from it. This halves runtime (detection
is ~92% of per-frame cost, measured in Track D) and, more importantly,
removes detection jitter as a confound: both arms see byte-identical
landmarks, so any difference between them is the thresholds alone. Each
variant gets its own landmark dict; extraction is ~0.03 ms and this removes
any question of shared-state mutation.

Usage:
    python reports/run_repcount_eval.py --sanity   # 2 known videos only
    python reports/run_repcount_eval.py            # full 185-video batch
"""
import argparse
import csv
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parents[1]))

import cv2
from src.pose.detector import PoseDetector
from src.exercises.generic_exercise import GenericExercise
from src.controller import EXERCISE_DEFINITIONS

ROOT = Path(__file__).parents[1]
GROUND_TRUTH_CSV = Path(__file__).parent / "ground_truth_counts.csv"
OUT_CSV = Path(__file__).parent / "evaluation_results_both_variants.csv"

# category -> (original definition name, percentile definition name)
#
# hammer_curl is deliberately scored with the BICEP CURL definition: it is a
# transfer test, not a category with its own definition. A hammer curl is the
# same elbow flexion with a rotated grip, so the question is whether one
# learned definition covers a movement variant it never saw.
#
# shoulder_press has no percentile counterpart -- it was trained AFTER the
# percentile change, so the shipped definition already uses percentile
# extremes and there is no min/max version to compare against. Both arms use
# the same definition and its rows are identical by construction.
VARIANTS = {
    "squat":               ("Learned Squat",   "Learned Squat (percentile)"),
    "push-up":             ("Learned Push-up", "Learned Push-up (percentile)"),
    "barbell_biceps_curl": ("BicepCurl",       "BicepCurl (percentile)"),
    "hammer_curl":         ("BicepCurl",       "BicepCurl (percentile)"),
    "shoulder_press":      ("ShoulderPress",   "ShoulderPress"),
}
NO_PERCENTILE_COUNTERPART = {"shoulder_press"}

# The two clips used to sanity-check the 14 July run before the full batch:
# a squat with the knees cropped out of frame (must count 0 of 6 -- the
# knee-visibility failure, not a script bug) and a clean home recording
# (must count 7 of 7).
SANITY = [
    ("squat", "Videos/squat/arc1_final_kaggle_with_additional_video_squat_1.MOV", 6, 0),
    ("squat", "Videos/Squats/man-home-squats.mp4",                                7, 7),
]


def accuracy_pct(detected: int, ground_truth: int) -> float:
    if ground_truth > 0:
        return max(0.0, (1 - abs(detected - ground_truth) / ground_truth) * 100)
    return 100.0 if detected == 0 else 0.0


def score_video(video_path: Path, category: str):
    """
    One detection pass; both variants scored from it.
    Returns {variant: result_dict} plus shared detection stats.
    """
    names = VARIANTS[category]
    exercises = {}
    for variant, defn_name in zip(("original", "percentile"), names):
        defn = EXERCISE_DEFINITIONS.get(defn_name)
        if defn is None:
            raise SystemExit(f"missing definition: {defn_name}")
        ex = GenericExercise(defn)
        ex.start()
        exercises[variant] = ex

    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        return None, f"cannot open video"
    src_fps = cap.get(cv2.CAP_PROP_FPS) or 30.0

    detector = PoseDetector()
    frames = frames_with_pose = 0
    prev_reps = {v: 0 for v in exercises}
    form_log = {v: [] for v in exercises}

    while True:
        ret, frame = cap.read()
        if not ret:
            break
        frames += 1

        pose_detected = detector.detect(frame)
        if pose_detected:
            frames_with_pose += 1
            ts = (frames / src_fps) * 1000
            for variant, ex in exercises.items():
                # Own dict per variant: extraction is ~0.03 ms and this
                # removes any shared-mutation question entirely.
                ex.analyze_pose(detector.get_all_landmarks_dict(frame.shape), ts)

        for variant, ex in exercises.items():
            reps = ex.get_rep_count()
            if reps > prev_reps[variant]:
                form_log[variant].append(ex.get_form_feedback().value)
                prev_reps[variant] = reps

    cap.release()
    detector.cleanup()

    shared = {
        "frames_processed": frames,
        "frames_with_pose": frames_with_pose,
        "detection_rate": round(100.0 * frames_with_pose / frames, 1) if frames else 0.0,
    }
    out = {}
    for variant, ex in exercises.items():
        counts = {r: form_log[variant].count(r)
                  for r in ("excellent", "good", "fair", "poor")}
        out[variant] = {
            "detected_reps": ex.get_rep_count(),
            "form_excellent": counts["excellent"],
            "form_good": counts["good"],
            "form_fair": counts["fair"],
            "form_poor": counts["poor"],
            **shared,
        }
    return out, None


def run_sanity():
    print("SANITY CHECK -- expected values are from the 14 July run\n")
    ok = True
    for category, rel, gt, expect_original in SANITY:
        path = ROOT / rel
        if not path.exists():
            print(f"  MISSING: {rel}")
            ok = False
            continue
        res, err = score_video(path, category)
        if err:
            print(f"  ERROR {rel}: {err}")
            ok = False
            continue
        o = res["original"]["detected_reps"]
        p = res["percentile"]["detected_reps"]
        verdict = "PASS" if o == expect_original else "FAIL"
        if o != expect_original:
            ok = False
        print(f"  {path.name:58} gt={gt}")
        print(f"     original   {o:>3} reps   (expected {expect_original})  {verdict}")
        print(f"     percentile {p:>3} reps")
        print(f"     detection  {res['original']['detection_rate']}%\n")
    print("SANITY:", "PASS" if ok else "FAIL")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sanity", action="store_true",
                    help="run only the two known-answer videos and stop")
    args = ap.parse_args()

    if args.sanity:
        sys.exit(0 if run_sanity() else 1)

    rows = list(csv.DictReader(open(GROUND_TRUTH_CSV)))
    todo = [r for r in rows
            if (r["ground_truth_reps"] or "").strip()
            and r["category"] in VARIANTS]
    print(f"{len(todo)} videos with ground truth across "
          f"{len(set(r['category'] for r in todo))} categories\n")

    out_rows = []
    t_start = time.time()
    for i, r in enumerate(todo, 1):
        path = ROOT / r["path"]
        gt = int(r["ground_truth_reps"])
        if not path.exists():
            print(f"  [{i}/{len(todo)}] MISSING {r['file']}")
            continue
        res, err = score_video(path, r["category"])
        if err:
            print(f"  [{i}/{len(todo)}] ERROR {r['file']}: {err}")
            for variant in ("original", "percentile"):
                out_rows.append({
                    "variant": variant, "category": r["category"], "file": r["file"],
                    "ground_truth_reps": gt, "detected_reps": "", "count_error": "",
                    "accuracy_pct": "", "frames_processed": "", "frames_with_pose": "",
                    "detection_rate": "", "form_excellent": "", "form_good": "",
                    "form_fair": "", "form_poor": "", "error": err,
                })
            continue

        line = []
        for variant in ("original", "percentile"):
            d = res[variant]
            acc = accuracy_pct(d["detected_reps"], gt)
            out_rows.append({
                "variant": variant,
                "category": r["category"],
                "file": r["file"],
                "ground_truth_reps": gt,
                "detected_reps": d["detected_reps"],
                "count_error": d["detected_reps"] - gt,
                "accuracy_pct": round(acc, 1),
                "frames_processed": d["frames_processed"],
                "frames_with_pose": d["frames_with_pose"],
                "detection_rate": d["detection_rate"],
                "form_excellent": d["form_excellent"],
                "form_good": d["form_good"],
                "form_fair": d["form_fair"],
                "form_poor": d["form_poor"],
                # carried through so subgroup analysis (unilateral curls,
                # machine vs dumbbell press, camera cuts) can be done from
                # this file alone rather than re-joining to the ground truth
                "notes": r.get("notes", ""),
                "error": "",
            })
            line.append(f"{variant[:4]}={d['detected_reps']}({acc:.0f}%)")
        flag = " *" if res["original"]["detected_reps"] != res["percentile"]["detected_reps"] else ""
        print(f"  [{i}/{len(todo)}] {r['file'][:52]:52} gt={gt:>2}  "
              f"{'  '.join(line)}{flag}")

    with open(OUT_CSV, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(out_rows[0].keys()))
        w.writeheader()
        w.writerows(out_rows)

    mins = (time.time() - t_start) / 60
    print(f"\nWrote {OUT_CSV.name} ({len(out_rows)} rows) in {mins:.1f} min")


if __name__ == "__main__":
    main()
